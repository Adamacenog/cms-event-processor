using System.Text.Json;
using CmsEventProcessor.Application.Identity.Contracts;
using CmsEventProcessor.Application.Identity.Models;

namespace CmsEventProcessor.Api.Provisioning;

/// <summary>
/// Runs explicit account initialization, addition, or rotation without starting the web host.
/// </summary>
internal static class CredentialCommand
{
    private const string Usage = """
        Explicit account provisioning (no web host is started):
          accounts init --file <appsettings.Local.json>
          accounts add --file <appsettings.Local.json> --kind <Cms|Reader|Admin>
          accounts rotate --file <appsettings.Local.json> --username <username>
        Newly generated passwords are displayed once. Save them securely.
        Restart the API after changing its account configuration.
        """;

    /// <summary>
    /// Executes a validated command and displays only passwords newly generated by that operation.
    /// </summary>
    /// <param name="args">The init, add, rotate, or help command and its explicit options, without the accounts prefix.</param>
    /// <param name="provisioner">The shared provisioning contract selected by the application composition root.</param>
    /// <param name="output">The operator output receiving usage or newly generated credentials once.</param>
    /// <param name="error">The diagnostic output receiving safe command and configuration errors.</param>
    /// <returns>Zero when the command succeeds or help is shown; one when a handled command or configuration error occurs.</returns>
    /// <exception cref="System.IO.IOException">The supplied output or diagnostic writer cannot be written.</exception>
    /// <exception cref="System.ObjectDisposedException">A required output or diagnostic writer has already been disposed.</exception>
    public static int Run(string[] args, IAccountProvisioner provisioner, TextWriter output, TextWriter error)
    {
        if (args.Length == 1 && args[0] is "--help" or "help")
        {
            output.WriteLine(Usage);
            return 0;
        }

        try
        {
            var options = Parse(args);
            IReadOnlyList<GeneratedCredential> credentials = args[0] switch
            {
                "init" when options.Count == 1 => provisioner.Initialize(options["--file"]),
                "rotate" when options.Count == 2 && options.TryGetValue("--username", out var username) =>
                    [provisioner.Rotate(options["--file"], username)],
                "add" when options.Count == 2 && options.TryGetValue("--kind", out var kind) &&
                    Enum.TryParse<AccountKind>(kind, ignoreCase: false, out var parsed) =>
                    [provisioner.Add(options["--file"], parsed)],
                _ => throw new ArgumentException("Invalid account command.")
            };

            output.WriteLine("Save these newly generated credentials securely. Passwords cannot be displayed again.");
            foreach (var credential in credentials)
            {
                output.WriteLine($"{credential.Account.Kind}: {credential.Account.Username}");
                output.WriteLine($"Password: {credential.Password}");
            }
            output.WriteLine("Configuration saved. Restart the API to load it.");
            return 0;
        }
        catch (ArgumentException)
        {
            error.WriteLine(Usage);
        }
        catch (InvalidOperationException exception)
        {
            error.WriteLine(exception.Message);
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or JsonException)
        {
            error.WriteLine("Unable to read or safely write the account configuration. Check its path, permissions, and JSON format.");
        }
        return 1;
    }

    /// <summary>
    /// Accepts only supported, unique option names and a nonblank configuration-file path.
    /// </summary>
    /// <param name="args">The command followed by unique option/value pairs.</param>
    /// <returns>The validated option dictionary, always including a nonblank file option.</returns>
    /// <exception cref="System.ArgumentException">Arguments are missing, duplicated, unsupported, or do not include a file option.</exception>
    private static Dictionary<string, string> Parse(string[] args)
    {
        if (args.Length < 3 || args.Length % 2 != 1)
        {
            throw new ArgumentException("Invalid arguments.");
        }
        var options = new Dictionary<string, string>(StringComparer.Ordinal);
        for (var index = 1; index < args.Length; index += 2)
        {
            if (args[index] is not ("--file" or "--username" or "--kind") ||
                string.IsNullOrWhiteSpace(args[index + 1]) || !options.TryAdd(args[index], args[index + 1]))
            {
                throw new ArgumentException("Invalid arguments.");
            }
        }
        if (!options.ContainsKey("--file"))
        {
            throw new ArgumentException("A configuration path is required.");
        }
        return options;
    }
}
