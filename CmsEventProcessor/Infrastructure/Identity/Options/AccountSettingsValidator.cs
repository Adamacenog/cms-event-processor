using System.Text.RegularExpressions;
using CmsEventProcessor.Application.Identity.Models;
using CmsEventProcessor.Infrastructure.Identity.Services;
using Microsoft.Extensions.Options;

namespace CmsEventProcessor.Infrastructure.Identity.Options;

/// <summary>
/// Rejects unsafe or incomplete configured identities before the web host accepts requests.
/// </summary>
internal sealed partial class AccountSettingsValidator : IValidateOptions<AccountSettings>
{
    /// <summary>
    /// Checks username uniqueness, supported hashes, valid kinds, and all three required identities.
    /// </summary>
    /// <param name="name">The optional options-instance name; the same validation applies to every name.</param>
    /// <param name="options">Stored account definitions to validate at startup or before explicit file changes.</param>
    /// <returns>Success for complete, valid configuration, or failure messages that do not echo credential values.</returns>
    public ValidateOptionsResult Validate(string? name, AccountSettings options)
    {
        if (options.Accounts is null || options.Accounts.Count == 0)
        {
            return ValidateOptionsResult.Fail("Authentication accounts are missing. Run accounts init or supply deployment secrets.");
        }

        var failures = new List<string>();
        var usernames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var account in options.Accounts)
        {
            if (account is null)
            {
                failures.Add("Account definitions cannot be null.");
                continue;
            }

            if (string.IsNullOrEmpty(account.Username) || !UsernamePattern().IsMatch(account.Username))
            {
                failures.Add("Usernames must contain 10-20 ASCII letters, digits, underscores, or hyphens.");
            }
            else if (!usernames.Add(account.Username))
            {
                failures.Add("Usernames must be unique across all account kinds.");
            }

            if (account.Kind is not (AccountKind.Cms or AccountKind.Reader or AccountKind.Admin))
            {
                failures.Add("Account kind must be Cms, Reader, or Admin.");
            }

            if (!PasswordHashService.IsSupportedHash(account.PasswordHash))
            {
                failures.Add("An account password hash is missing or unsupported. Provision credentials using the setup command.");
            }
        }

        foreach (var kind in new[] { AccountKind.Cms, AccountKind.Reader, AccountKind.Admin })
        {
            if (!options.Accounts.Any(account => account?.Kind == kind))
            {
                failures.Add($"At least one {kind} account is required.");
            }
        }

        return failures.Count == 0 ? ValidateOptionsResult.Success : ValidateOptionsResult.Fail(failures);
    }

    /// <summary>
    /// Matches the bounded ASCII usernames generated by the provisioning utility.
    /// </summary>
    /// <returns>The generated regex accepting 10-20 ASCII letters, digits, underscores, or hyphens.</returns>
    [GeneratedRegex("\\A[A-Za-z0-9_-]{10,20}\\z", RegexOptions.CultureInvariant)]
    private static partial Regex UsernamePattern();
}
